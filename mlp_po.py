def run_comparative_pipeline(ticker):
    print(f"\n--- Memproses {ticker} ---")
    df = fetch_data(ticker)

    # Buat Sliding Window
    X, y = create_sliding_window(df, window_size=WINDOW_SIZE)
    print(f"Bentuk X setelah sliding window: {X.shape}") # (samples, 30, 4)

    # Simpan harga Close asli untuk rekonstruksi
    close_prices = df["Close"].values[WINDOW_SIZE:].ravel() # Pastikan 1D

    X_tr, y_tr, X_val, y_val, X_te, y_te, sx, sy = split_and_scale(X, y)

    # 1. Latih Puma Optimizer (Menggunakan fungsi wrapper)
    print("Melatih dengan Puma Optimizer...")
    start_po = time.time()
    theta, f_best, eefo_log = po_optimize(X_tr, y_tr, X_val, y_val)
    time_eefo = time.time() - start_po

    # 2. Latih Backprop
    print("Melatih dengan Backpropagation (Adam)...")
    model_bp, bp_log, time_bp = train_mlp_backprop(X_tr, y_tr, X_val, y_val, epochs=200, lr=0.01)

    # 3. Rekonstruksi Harga
    n = len(X)
    tr_end, val_end = int(0.70 * n), int(0.85 * n)

    # Index untuk test set
    close_yesterday_test = close_prices[val_end : -1].ravel()
    close_actual_test = close_prices[val_end + 1 :].ravel()

    y_pred_eefo_log_ret = sy.inverse_transform(mlp_forward(theta, X_te)).ravel()

    model_bp.eval()
    with torch.no_grad():
        y_pred_bp_log_ret = sy.inverse_transform(model_bp(torch.FloatTensor(X_te.reshape(X_te.shape[0], -1))).numpy()).ravel()

    y_pred_eefo_price = (close_yesterday_test * np.exp(y_pred_eefo_log_ret)).ravel()
    y_pred_bp_price = (close_yesterday_test * np.exp(y_pred_bp_log_ret)).ravel()
    y_true_price = close_actual_test.ravel()

    # 4. Metrik
    def calc_metrics(y_true, y_pred):
        return {
            "RMSE": np.sqrt(mean_squared_error(y_true, y_pred)),
            "MAE": mean_absolute_error(y_true, y_pred),
            "MAPE": np.mean(np.abs((y_true - y_pred) / y_true)) * 100,
            "R2": r2_score(y_true, y_pred)
        }

    metrics_eefo = calc_metrics(y_true_price, y_pred_eefo_price)
    metrics_bp = calc_metrics(y_true_price, y_pred_bp_price)

    print(f"Waktu EEFO: {time_eefo:.2f} detik | Waktu BP: {time_bp:.2f} detik")
    print(f"Metrik EEFO: {metrics_eefo}")
    print(f"Metrik BP  : {metrics_bp}")

    return {
        "eefo": {"metrics": metrics_eefo, "time": time_eefo, "log": eefo_log, "pred": y_pred_eefo_price},
        "bp": {"metrics": metrics_bp, "time": time_bp, "log": bp_log, "pred": y_pred_bp_price},
        "y_true": y_true_price
    }

