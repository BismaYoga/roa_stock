class PumaState:
    """
    Manages the historical performance memory and phase-switching logic
    for the Puma Optimizer.
    """
    def __init__(self):
        # Weights for the scoring functions (PF_1, PF_2, PF_3)
        self.PF = np.array([0.67, 0.67, 0.42])

        # Historical arrays for the last 3 steps [t, t-1, t-2]
        self.time_explore = np.ones(3)
        self.time_exploit = np.ones(3)
        self.cost_explore = np.ones(3)
        self.cost_exploit = np.ones(3)

        # Unselected counters [explore, exploit]
        self.unselected = np.ones(2)

        # F3 Accumulators (Diversification components)
        self.F3_explore = 0.0
        self.F3_exploit = 0.0

        # Adaptive Weights
        self.mega_explore = 0.99
        self.mega_exploit = 0.99

        self.pf_f3_history = []
        self.current_phase = 1 # 1 = Explore, 2 = Exploit

    def shift_history(self, cost_history, time_history, new_cost, unselected_count):
        """Helper to shift the [t-2, t-1, t] arrays back in time."""
        cost_history[2] = cost_history[1]
        cost_history[1] = cost_history[0]
        cost_history[0] = new_cost

        time_history[2] = time_history[1]
        time_history[1] = time_history[0]
        time_history[0] = unselected_count

    def calculate_scores(self):
        """Calculates F1, F2, and the final Score for both phases."""
        # F1: Immediate return on investment
        f1_explore = self.PF[0] * (self.cost_explore[0] / self.time_explore[0])
        f1_exploit = self.PF[0] * (self.cost_exploit[0] / self.time_exploit[0])

        # F2: Historical return on investment
        f2_explore = self.PF[1] * (np.sum(self.cost_explore) / np.sum(self.time_explore))
        f2_exploit = self.PF[1] * (np.sum(self.cost_exploit) / np.sum(self.time_exploit))

        # F3: Minimum observed nonzero cost change
        min_pf_f3 = min(self.pf_f3_history) if self.pf_f3_history else 0.0

        lmn_explore = 1 - self.mega_explore
        lmn_exploit = 1 - self.mega_exploit

        score_explore = (self.mega_explore * f1_explore) + (self.mega_explore * f2_explore) + (lmn_explore * min_pf_f3 * self.F3_explore)
        score_exploit = (self.mega_exploit * f1_exploit) + (self.mega_exploit * f2_exploit) + (lmn_exploit * min_pf_f3 * self.F3_exploit)

        return score_explore, score_exploit

    def adapt_weights(self, score_explore, score_exploit):
        """Adjusts the 'Mega' weights based on which score is winning."""
        if score_explore < score_exploit:
            # Explore is losing: penalize explore, reset exploit
            self.mega_explore = max(self.mega_explore - 0.01, 0.01)
            self.mega_exploit = 0.99

        elif score_explore > score_exploit:
            # Exploit is losing: penalize exploit, reset explore
            self.mega_explore = 0.99
            self.mega_exploit = max(self.mega_exploit - 0.01, 0.01)

def run_puma_optimizer(n_agents, max_iter, dim, lower_bound, upper_bound, cost_function, seed=42):
    rng = np.random.default_rng(seed)

    # Initialization
    population = rng.uniform(lower_bound, upper_bound, size=(n_agents, dim))
    fitness = np.zeros(n_agents)
    for i in range(n_agents):
        fitness[i] = cost_function(population[i])

    best_idx = np.argmin(fitness)
    global_best_pos = population[best_idx].copy()
    global_best_cost = fitness[best_idx]

    convergence_curve = np.zeros(max_iter)

    population_history = []

    state = PumaState()
    pCR = 0.20

    print("\n--- Starting Puma Optimization ---")

    for iteration in range(max_iter):

        if iteration < 3:
            # ---------------------------------------------------------
            # UNEXPERIENCED PHASE: Strict fidelity to MATLAB/PO Paper
            # ---------------------------------------------------------
            # 1. Run Exploration Branch
            pop_explor, fit_explor, pCR = exploration_phase(
                population, fitness, lower_bound, upper_bound, cost_function, pCR, rng
            )
            best_explor_cost = np.min(fit_explor)

            # 2. Run Exploitation Branch
            pop_exploit, fit_exploit = exploitation_phase(
                population, fitness, lower_bound, upper_bound, global_best_pos,
                iteration, max_iter, cost_function, rng
            )
            best_exploit_cost = np.min(fit_exploit)

            # 3. Pool and Sort (Sol + Sol_Explor + Sol_Exploit)
            all_pops = np.vstack((population, pop_explor, pop_exploit))
            all_fits = np.concatenate((fitness, fit_explor, fit_exploit))

            # Sort all 3N agents by fitness and keep only the top N
            sorted_indices = np.argsort(all_fits)[:n_agents]
            population = all_pops[sorted_indices]
            fitness = all_fits[sorted_indices]

            # 4. Update history arrays for BOTH phases
            cost_diff_explor = abs(global_best_cost - best_explor_cost)
            cost_diff_exploit = abs(global_best_cost - best_exploit_cost)

            state.shift_history(state.cost_explore, state.time_explore, cost_diff_explor, 1)
            state.shift_history(state.cost_exploit, state.time_exploit, cost_diff_exploit, 1)

            if cost_diff_explor > 0: state.pf_f3_history.append(cost_diff_explor)
            if cost_diff_exploit > 0: state.pf_f3_history.append(cost_diff_exploit)

            phase_str = "Unexperienced (Both)"

        else:
            # ---------------------------------------------------------
            # EXPERIENCED PHASE: Adaptive Phase Switching
            # ---------------------------------------------------------
            score_explore, score_exploit = state.calculate_scores()

            if score_explore > score_exploit:
                population, fitness, pCR = exploration_phase(
                    population, fitness, lower_bound, upper_bound, cost_function, pCR, rng
                )

                # Update State Trackers
                state.unselected[1] += 1
                state.F3_explore = state.PF[2]
                state.F3_exploit += state.PF[2]

                iter_best_idx = np.argmin(fitness)
                cost_diff = abs(global_best_cost - fitness[iter_best_idx])

                state.shift_history(state.cost_explore, state.time_explore, cost_diff, state.unselected[0])
                state.unselected[0] = 1
                if cost_diff > 0: state.pf_f3_history.append(cost_diff)
                phase_str = "Experienced (Explore)"

            else:
                population, fitness = exploitation_phase(
                    population, fitness, lower_bound, upper_bound, global_best_pos,
                    iteration, max_iter, cost_function, rng
                )

                # Update State Trackers
                state.unselected[0] += 1
                state.F3_exploit = state.PF[2]
                state.F3_explore += state.PF[2]

                iter_best_idx = np.argmin(fitness)
                cost_diff = abs(global_best_cost - fitness[iter_best_idx])

                state.shift_history(state.cost_exploit, state.time_exploit, cost_diff, state.unselected[1])
                state.unselected[1] = 1
                if cost_diff > 0: state.pf_f3_history.append(cost_diff)
                phase_str = "Experienced (Exploit)"

            # Adapt weights for the next round
            state.adapt_weights(score_explore, score_exploit)

        # Update Global Best
        current_best_idx = np.argmin(fitness)
        if fitness[current_best_idx] < global_best_cost:
            global_best_cost = fitness[current_best_idx]
            global_best_pos = population[current_best_idx].copy()

        convergence_curve[iteration] = global_best_cost
        print(f"Iteration {iteration + 1}/{max_iter} - Phase: {phase_str} - Best Loss: {global_best_cost:.6f}")
        population_history.append(population.copy())

    return global_best_pos, global_best_cost, convergence_curve, population_history

def exploration_phase(population, fitness, lower_bound, upper_bound, cost_function, pCR, rng):
    """
    Executes the Global Search (Exploration) phase using Differential Evolution logic.
    """
    n_agents, dim = population.shape
    new_population = population.copy()

    # Base crossover increment factor from the PO paper
    p = (1 - pCR) / n_agents

    for i in range(n_agents):
        # 1. Pick 6 random distinct agents (excluding current agent 'i')
        indices = np.delete(np.arange(n_agents), i)
        a, b, c, d, e, f = rng.choice(indices, size=6, replace=False)

        # 2. Extract their positions
        xa, xb, xc = population[a], population[b], population[c]
        xd, xe, xf = population[d], population[e], population[f]

        # 3. Calculate the Differential Mutation
        G = 2 * rng.random() - 1
        if rng.random() < 0.5:
            # Pure random search jump
            y = rng.uniform(lower_bound, upper_bound, size=dim)
        else:
            # Puma differential search jump
            term1 = xa - xb
            term2 = (xa - xb) - (xc - xd)
            term3 = (xc - xd) - (xe - xf)
            y = xa + G * term1 + G * (term2 + term3)

        # Enforce boundaries
        y = np.clip(y, lower_bound, upper_bound)

        # 4. Crossover: Mix the mutated vector 'y' with the original vector 'x'
        z = population[i].copy()
        j_rand = rng.integers(0, dim) # Guarantee at least one mutated feature

        for j in range(dim):
            if j == j_rand or rng.random() <= pCR:
                z[j] = y[j]

        # 5. Greedy Selection: Keep the new position only if it improves the loss
        new_cost = cost_function(z)
        if new_cost < fitness[i]:
            new_population[i] = z
            fitness[i] = new_cost
        else:
            # PO adaptively increases crossover probability if the search fails
            pCR += p

    return new_population, fitness, pCR

def exploitation_phase(population, fitness, lower_bound, upper_bound, global_best_pos, current_iter, max_iter, cost_function, rng):
    """
    Executes the Local Search (Exploitation) phase using Puma attack mechanics.
    """
    n_agents, dim = population.shape
    new_population = population.copy()

    Q = 0.67  # 'L' from the PO paper: branch threshold
    beta = 2  # 'a' from the PO paper: denominator scaling factor

    # Calculate the mean position across all coordinates of all agents
    # (Preserving the specific MATLAB behavior where mean is a single scalar)
    mbest = np.mean(population) / n_agents

    for i in range(n_agents):
        current_pos = population[i]

        # 1. Generate random PO scaling vectors
        beta1 = 2 * rng.random()
        beta2 = rng.standard_normal(dim)
        w = rng.standard_normal(dim)
        v = rng.standard_normal(dim)

        F1_vec = rng.standard_normal(dim) * np.exp(2 - current_iter * (2 / max_iter))
        F2_vec = w * (v**2) * np.cos((2 * rng.random()) * w)
        R_1 = 2 * rng.random() - 1

        # 2. Calculate the "Attack Vector" (VEC)
        # This translates MATLAB's matrix right-division (S2 / S1) to Python dot products
        S1 = (2 * rng.random() - 1) + rng.standard_normal(dim)
        S2 = (F1_vec * R_1 * current_pos) + (F2_vec * (1 - R_1) * global_best_pos)

        denominator = np.dot(S1, S1)
        # Prevent division by zero
        vec_attack = np.dot(S2, S1) / denominator if denominator != 0 else 0.0

        # 3. Apply the Puma Movement Logic
        if rng.random() <= 0.5:
            if rng.random() > Q:
                r2 = rng.integers(0, n_agents)
                new_x = global_best_pos + beta1 * np.exp(beta2) * (population[r2] - current_pos)
            else:
                new_x = beta1 * vec_attack - global_best_pos
        else:
            r1 = rng.integers(0, n_agents)
            sign_flip = rng.choice([-1, 1])
            new_x = (mbest * population[r1] - sign_flip * current_pos) / (1 + beta * rng.random())

        # 4. Enforce boundaries
        new_x = np.clip(new_x, lower_bound, upper_bound)

        # 5. Greedy Selection
        new_cost = cost_function(new_x)
        if new_cost < fitness[i]:
            new_population[i] = new_x
            fitness[i] = new_cost

    # ADD THIS RETURN STATEMENT AT THE END (aligned with the outer for-loop)
    return new_population, fitness

