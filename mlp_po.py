WINDOW_SIZE = 10
N_FEATURES = 6  # Explicitly updated to 6 to include all your downloaded columns
FLATTEN_SIZE = WINDOW_SIZE * N_FEATURES

# Calculate Total Parameters (D) dynamically
w1_params = (FLATTEN_SIZE * 128) + 128
w2_params = (128 * 64) + 64
w3_params = (64 * 32) + 32
w4_params = (32 * 1) + 1

D = w1_params + w2_params + w3_params + w4_params
print(f"[*] Dynamic Total Parameters (D): {D}")

def unpack(theta):
    i = 0
    # Layer 1
    W1 = theta[i:i + (FLATTEN_SIZE * 128)].reshape(FLATTEN_SIZE, 128); i += (FLATTEN_SIZE * 128)
    b1 = theta[i:i + 128]; i += 128
    # Layer 2
    W2 = theta[i:i + (128 * 64)].reshape(128, 64); i += (128 * 64)
    b2 = theta[i:i + 64]; i += 64
    # Layer 3
    W3 = theta[i:i + (64 * 32)].reshape(64, 32); i += (64 * 32)
    b3 = theta[i:i + 32]; i += 32
    # Output Layer
    W4 = theta[i:i + 32].reshape(32, 1); i += 32
    b4 = theta[i:i + 1]
    return W1, b1, W2, b2, W3, b3, W4, b4

def mlp_forward(theta, X):
    # X berbentuk (samples, 30, 4) -> kita ratakan (flatten) menjadi (samples, 120)
    X_flat = X.reshape(X.shape[0], -1)
    W1, b1, W2, b2, W3, b3, W4, b4 = unpack(theta)

    # Forward pass melalui 3 hidden layer
    h1 = np.tanh(X_flat @ W1 + b1)
    h2 = np.tanh(h1 @ W2 + b2)
    h3 = np.tanh(h2 @ W3 + b3)
    out = h3 @ W4 + b4
    return out

def fitness(theta, X, y):
    mse = np.mean((y - mlp_forward(theta, X)) ** 2)
    return np.sqrt(mse)

"""# 3. PO OPTIMIZER"""

def create_po_cost(X, y):
    """Wraps the existing fitness function so PO only passes 'theta'."""
    def cost_function(theta):
        return fitness(theta, X, y)
    return cost_function

def po_optimize(X_train, y_train, X_val, y_val, N=150, T=200, bounds=(-1.0, 1.0), seed=67, patience=40):
    # Note: We keep the function name '' to avoid breaking the pipeline,
    # but we execute the Puma Optimizer inside.

    # 1. Lock in the training data for the cost function
    train_cost = create_po_cost(X_train, y_train)

    # 2. Execute Puma Optimizer
    best_theta, best_cost, convergence_curve, _ = run_puma_optimizer(
        n_agents=N,
        max_iter=T,
        dim=D,  # Uses the global D (25857) defined in your script
        lower_bound=bounds[0],
        upper_bound=bounds[1],
        cost_function=train_cost,
        seed=seed
    )

    # 3. Calculate final validation fitness for the return signature
    best_val_cost = fitness(best_theta, X_val, y_val)

    # Return best weights, validation score, and convergence history
    return best_theta, best_val_cost, convergence_curve

