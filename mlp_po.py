"""# 4. BACKPROPAGATION (Adam) DENGAN 3 HIDDEN LAYERS"""

def train_mlp_backprop(X_train, y_train, X_val, y_val, epochs=100, lr=0.01):
    X_tr_t = torch.FloatTensor(X_train.reshape(X_train.shape[0], -1))
    y_tr_t = torch.FloatTensor(y_train)
    X_val_t = torch.FloatTensor(X_val.reshape(X_val.shape[0], -1))
    y_val_t = torch.FloatTensor(y_val)

    class MLP(nn.Module):
        def __init__(self):
            super(MLP, self).__init__()
            self.net = nn.Sequential(
                nn.Linear(FLATTEN_SIZE, 128),
                nn.Tanh(),
                nn.Linear(128, 64),
                nn.Tanh(),
                nn.Linear(64, 32),
                nn.Tanh(),
                nn.Linear(32, 1)
            )
        def forward(self, x):
            return self.net(x)

    model = MLP()
    criterion = nn.MSELoss()
    optimizer = optim.Adam(model.parameters(), lr=lr)

    history_mse = []
    start_time = time.time()

    for epoch in range(epochs):
        model.train()
        optimizer.zero_grad()
        y_pred = model(X_tr_t)
        loss = criterion(y_pred, y_tr_t)
        loss.backward()
        optimizer.step()

        if epoch % 10 == 0 or epoch == epochs - 1:
            model.eval()
            with torch.no_grad():
                val_pred = model(X_val_t)
                val_loss = criterion(val_pred, y_val_t).item()
                history_mse.append(val_loss)

    train_time = time.time() - start_time
    return model, history_mse, train_time

