def fetch_data(ticker, period="5y", interval="1d"):
    df = yf.download(ticker, period=period, interval=interval, auto_adjust=False)
    return df[["Open", "High", "Low", "Close", "Adj Close", "Volume"]].dropna()

def create_sliding_window(df, window_size=30):
    """
    Mengubah data tabular menjadi format 3D sliding window.
    Input: df (DataFrame harga)
    Output: X (samples, window_size, features), y (target log return)
    """
    data = df.values
    target = np.log(df["Close"] / df["Close"].shift(1)).values # Log Return sebagai target

    X, y = [], []
    # Mulai dari window_size karena kita butuh data masa lalu
    for i in range(window_size, len(data) - 1):
        X.append(data[i-window_size:i, :]) # Ambil 30 hari ke belakang
        y.append(target[i+1])              # Prediksi return besok

    return np.array(X), np.array(y).reshape(-1, 1)

def split_and_scale(X, y):
    n = len(X)
    tr_end, val_end = int(0.70 * n), int(0.85 * n)

    X_tr, y_tr = X[:tr_end], y[:tr_end]
    X_val, y_val = X[tr_end:val_end], y[tr_end:val_end]
    X_te, y_te = X[val_end:], y[val_end:]

    # Scaling (Fit hanya di Train)
    # Karena X berbentuk 3D (samples, window, features), kita perlu reshape sementara ke 2D
    n_samples, window, n_feats = X.shape
    X_tr_2d = X_tr.reshape(-1, n_feats)
    sx = MinMaxScaler().fit(X_tr_2d)

    sy = MinMaxScaler().fit(y_tr)

    # Transform dan kembalikan ke bentuk 3D
    X_tr_scaled = sx.transform(X_tr.reshape(-1, n_feats)).reshape(X_tr.shape)
    X_val_scaled = sx.transform(X_val.reshape(-1, n_feats)).reshape(X_val.shape)
    X_te_scaled = sx.transform(X_te.reshape(-1, n_feats)).reshape(X_te.shape)

    return (X_tr_scaled, sy.transform(y_tr),
            X_val_scaled, sy.transform(y_val),
            X_te_scaled, sy.transform(y_te), sx, sy)

