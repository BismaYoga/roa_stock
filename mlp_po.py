def export_research_data_to_csv(results_compare, tickers):
    import pandas as pd
    print("\n[*] Exporting all evaluation metrics and predictions to CSV...")

    # 1. Export Metrics
    metrics_data = []
    for ticker in tickers:
        for method in ["eefo", "bp"]:
            metrics = results_compare[ticker][method]["metrics"]
            metrics_data.append({
                "Ticker": ticker,
                "Method": "Puma Optimizer (PO)" if method == "eefo" else "Backprop (Adam)",
                "RMSE": metrics["RMSE"],
                "MAE": metrics["MAE"],
                "MAPE": metrics["MAPE"],
                "R2": metrics["R2"],
                "Training_Time_Sec": results_compare[ticker][method]["time"]
            })
    pd.DataFrame(metrics_data).to_csv("evaluation_metrics_summary.csv", index=False)

    # 2. Export Forecasts
    forecast_data = []
    for ticker in tickers:
        y_true = results_compare[ticker]["y_true"].ravel()
        y_po = results_compare[ticker]["eefo"]["pred"].ravel()
        y_bp = results_compare[ticker]["bp"]["pred"].ravel()

        df_ticker = pd.DataFrame({
            "Ticker": ticker,
            "Test_Day": range(1, len(y_true) + 1),
            "Actual_Price": y_true,
            "PO_Predicted_Price": y_po,
            "Backprop_Predicted_Price": y_bp
        })
        forecast_data.append(df_ticker)
    pd.concat(forecast_data, ignore_index=True).to_csv("actual_vs_predicted_forecasts.csv", index=False)

    # 3. Export Convergence
    convergence_data = []
    for ticker in tickers:
        po_log = results_compare[ticker]["eefo"]["log"]
        convergence_data.append(pd.DataFrame({
            "Ticker": ticker, "Method": "Puma Optimizer (PO)",
            "Iteration": range(1, len(po_log) + 1), "MSE_Loss": po_log
        }))

        bp_log = results_compare[ticker]["bp"]["log"]
        convergence_data.append(pd.DataFrame({
            "Ticker": ticker, "Method": "Backprop (Adam)",
            "Logged_Step": range(1, len(bp_log) + 1), "MSE_Loss": bp_log
        }))
    pd.concat(convergence_data, ignore_index=True).to_csv("training_convergence_history.csv", index=False)
    print("[+] CSV exports complete.")

